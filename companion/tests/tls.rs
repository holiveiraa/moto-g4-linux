//! Fresh test-only CA/leaf: real HTTPS and WSS, never an owner's certificate.
use moto_hermes::{config::Config, net::Backend, storage};
use std::{
    fs,
    io::{BufRead, BufReader, Write},
    net::{TcpListener, TcpStream},
    path::{Path, PathBuf},
    process::{Command, Stdio},
    sync::{
        atomic::{AtomicBool, Ordering},
        Arc,
    },
    thread,
    time::Duration,
};

struct TlsFixture {
    root: PathBuf,
    port: u16,
    stop: Arc<AtomicBool>,
    task: Option<thread::JoinHandle<()>>,
}
fn openssl(root: &Path, args: &[&str]) {
    assert!(Command::new("openssl")
        .args(args)
        .current_dir(root)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .expect("TLS fixtures require openssl")
        .success());
}
impl TlsFixture {
    fn new() -> Self {
        let _ = rustls::crypto::ring::default_provider().install_default();
        let root = std::env::temp_dir().join(format!("moto-hermes-tls-{}", storage::id().unwrap()));
        fs::create_dir(&root).unwrap();
        if let Some(prepared) = std::env::var_os("MOTO_HERMES_TLS_FIXTURE") {
            // Cross-device reviews may lack an OpenSSL CLI. These must be fresh
            // synthetic localhost certificates generated by the review, never
            // an owner's CA/key or a production certificate.
            let prepared = PathBuf::from(prepared);
            for name in ["ca.pem", "leaf.pem", "leaf.key"] {
                fs::copy(prepared.join(name), root.join(name)).unwrap();
            }
        } else {
            openssl(
                &root,
                &[
                    "req",
                    "-x509",
                    "-newkey",
                    "rsa:2048",
                    "-nodes",
                    "-days",
                    "1",
                    "-subj",
                    "/CN=Moto test CA",
                    "-keyout",
                    "ca.key",
                    "-out",
                    "ca.pem",
                    "-addext",
                    "basicConstraints=critical,CA:TRUE",
                ],
            );
            openssl(
                &root,
                &[
                    "req",
                    "-new",
                    "-newkey",
                    "rsa:2048",
                    "-nodes",
                    "-subj",
                    "/CN=localhost",
                    "-keyout",
                    "leaf.key",
                    "-out",
                    "leaf.csr",
                ],
            );
            fs::write(root.join("leaf.ext"), "subjectAltName=DNS:localhost\nbasicConstraints=critical,CA:FALSE\nkeyUsage=digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\n").unwrap();
            openssl(
                &root,
                &[
                    "x509",
                    "-req",
                    "-in",
                    "leaf.csr",
                    "-CA",
                    "ca.pem",
                    "-CAkey",
                    "ca.key",
                    "-CAcreateserial",
                    "-days",
                    "1",
                    "-extfile",
                    "leaf.ext",
                    "-out",
                    "leaf.pem",
                ],
            );
        }
        let certs = rustls_pemfile::certs(&mut fs::read(root.join("leaf.pem")).unwrap().as_slice())
            .collect::<std::result::Result<Vec<_>, _>>()
            .unwrap();
        let key =
            rustls_pemfile::private_key(&mut fs::read(root.join("leaf.key")).unwrap().as_slice())
                .unwrap()
                .unwrap();
        let tls = Arc::new(
            rustls::ServerConfig::builder()
                .with_no_client_auth()
                .with_single_cert(certs, key)
                .unwrap(),
        );
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        listener.set_nonblocking(true).unwrap();
        let port = listener.local_addr().unwrap().port();
        let stop = Arc::new(AtomicBool::new(false));
        let stopper = stop.clone();
        let task = thread::spawn(move || {
            let mut children = Vec::new();
            while !stopper.load(Ordering::SeqCst) {
                match listener.accept() {
                    Ok((stream, _)) => {
                        let tls = tls.clone();
                        children.push(thread::spawn(move || serve(stream, tls)));
                    }
                    Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                        thread::sleep(Duration::from_millis(5))
                    }
                    Err(_) => break,
                }
            }
            for child in children {
                child.join().unwrap();
            }
        });
        Self {
            root,
            port,
            stop,
            task: Some(task),
        }
    }
    fn backend(&self, host: &str, trust: bool) -> Backend {
        let mut config = Config::for_server(&format!("https://{host}:{}/", self.port)).unwrap();
        if trust {
            config.ca_file = Some(self.root.join("ca.pem"));
        }
        Backend::new(config, &self.root).unwrap()
    }
}
impl Drop for TlsFixture {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::SeqCst);
        self.task.take().unwrap().join().unwrap();
        fs::remove_dir_all(&self.root).unwrap();
    }
}
fn serve(stream: TcpStream, config: Arc<rustls::ServerConfig>) {
    stream
        .set_read_timeout(Some(Duration::from_secs(3)))
        .unwrap();
    stream
        .set_write_timeout(Some(Duration::from_secs(3)))
        .unwrap();
    let mut conn = rustls::ServerConnection::new(config).unwrap();
    let mut socket = stream;
    while conn.is_handshaking() {
        if conn.complete_io(&mut socket).is_err() {
            return;
        }
    }
    let mut stream = rustls::StreamOwned::new(conn, socket);
    let mut request = Vec::new();
    {
        let mut reader = BufReader::new(&mut stream);
        loop {
            let mut line = Vec::new();
            if reader.read_until(b'\n', &mut line).unwrap_or(0) == 0 {
                return;
            }
            if line == b"\r\n" {
                request.extend(line);
                break;
            }
            request.extend(line);
            if request.len() > 8192 {
                return;
            }
        }
    }
    if String::from_utf8_lossy(&request)
        .to_lowercase()
        .contains("upgrade: websocket")
    {
        // Re-feed only the public handshake bytes consumed to classify HTTP/WSS.
        struct Replay<S> {
            prefix: std::io::Cursor<Vec<u8>>,
            stream: S,
        }
        impl<S: std::io::Read> std::io::Read for Replay<S> {
            fn read(&mut self, out: &mut [u8]) -> std::io::Result<usize> {
                let n = std::io::Read::read(&mut self.prefix, out)?;
                if n > 0 {
                    Ok(n)
                } else {
                    self.stream.read(out)
                }
            }
        }
        impl<S: Write> Write for Replay<S> {
            fn write(&mut self, data: &[u8]) -> std::io::Result<usize> {
                self.stream.write(data)
            }
            fn flush(&mut self) -> std::io::Result<()> {
                self.stream.flush()
            }
        }
        if let Ok(mut ws) = tungstenite::accept(Replay {
            prefix: std::io::Cursor::new(request),
            stream,
        }) {
            let _ = ws.close(None);
        }
    } else {
        let html = "<script>window.__HERMES_SESSION_TOKEN__=\"fixture-tls-token\";</script>";
        let _ = write!(
            stream,
            "HTTP/1.1 200 OK\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{html}",
            html.len()
        );
        let _ = stream.flush();
    }
}

#[test]
fn https_and_wss_share_ca_and_enforce_hostname_validation() {
    let fixture = TlsFixture::new();
    for (host, trust, allowed) in [
        ("localhost", false, false),
        ("127.0.0.1", true, false),
        ("localhost", true, true),
    ] {
        let backend = fixture.backend(host, trust);
        assert_eq!(
            backend.discover().is_ok(),
            allowed,
            "HTTPS {host} custom CA={trust}"
        );
        assert_eq!(
            backend.socket("/api/ws", "fixture-tls-token").is_ok(),
            allowed,
            "WSS {host} custom CA={trust}"
        );
    }
}
